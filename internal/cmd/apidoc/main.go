// Command apidoc generates docs/API.md: one page listing every exported
// symbol in every public package, with its doc comment's first sentence.
//
// It is GENERATED rather than written, and that is the whole point. A
// hand-maintained API list rots the moment a signature changes, and this
// repository has already watched a hand-written section describe a
// feature as unimplemented an hour after it shipped. Regenerating is a
// command; noticing that prose went stale is not.
//
// It complements pkg.go.dev rather than replacing it: that renders full
// documentation for one package at a time, while this is the one page
// that answers "what is in this library, and where does it live".
//
//	go run ./internal/cmd/apidoc > docs/API.md
package main

import (
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// packages are the public surface, in the order a reader meets them
// rather than alphabetically: what a schema is, then how to write one,
// then how to run it, then what comes out, then everything else.
var packages = []struct {
	dir, blurb string
}{
	{"vb", "Write rules. The typed builder every schema starts from."},
	{"interp", "Run rules by reflection: the default executor."},
	{"verr", "What a failure looks like: issues, codes, and errors.Is."},
	{"ir", "The rule tree itself, as data. Read this to author or read a schema by hand."},
	{"jsonschema", "Export to JSON Schema, plus the manifest of what could not cross."},
	{"i18n", "Message catalogs, shared with the TypeScript runtime."},
	{"rulehttp", "Serve async rules over HTTP for the browser round-trip."},
	{"codegen", "Generate a reflection-free validator."},
	{"codegen/rt", "The tiny runtime generated code imports."},
	{"accessors", "Generate typed field accessors from your structs."},
	{"tags", "Migrate go-playground struct tags into the IR."},
	{"cel", "Optional expression engine, its own module."},
}

func main() {
	var b strings.Builder
	b.WriteString("# API reference\n\n")
	b.WriteString("Generated by `go run ./internal/cmd/apidoc > docs/API.md`. Do not edit by hand: a list maintained by hand goes stale, and this one cannot.\n\n")
	b.WriteString("Every exported symbol, by package, with the first sentence of its documentation. For full prose, examples and method sets, see [pkg.go.dev](https://pkg.go.dev/github.com/ubgo/validator), or run `go doc` on any symbol below.\n\n")
	b.WriteString("Start with the [guide](GUIDE.md) if you have not read it: this page assumes you know what a schema is.\n\n")

	b.WriteString("## Packages\n\n| Package | What it is for |\n|---|---|\n")
	for _, p := range packages {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", p.dir, anchor(p.dir), p.blurb)
	}
	b.WriteString("\n")

	for _, p := range packages {
		section, err := render(p.dir, p.blurb)
		if err != nil {
			fmt.Fprintf(os.Stderr, "apidoc: %s: %v\n", p.dir, err)
			os.Exit(1)
		}
		b.WriteString(section)
	}
	fmt.Print(b.String())
}

// anchor is GitHub's heading-to-fragment rule for the names here: lower
// case, slashes dropped.
func anchor(dir string) string {
	return strings.ReplaceAll(strings.ToLower(dir), "/", "")
}

// render builds one package's section from its parsed documentation.
func render(dir, blurb string) (string, error) {
	// doc.NewFromFiles rather than parser.ParseDir + doc.New: ast.Package
	// and doc.New are deprecated, and this path also resolves doc links.
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return "", err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return "", fmt.Errorf("no Go files in %s", dir)
	}
	d, err := doc.NewFromFiles(fset, files, "./"+dir, doc.AllDecls)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "## %s\n\n", dir)
	fmt.Fprintf(&b, "%s\n\n", blurb)
	fmt.Fprintf(&b, "```go\nimport \"github.com/ubgo/validator/%s\"\n```\n\n", importPath(dir))

	writeRows(&b, "Functions", funcRows(d, d.Funcs))
	for _, t := range d.Types {
		rows := []row{{code(typeLine(t)), first(d, t.Doc)}}
		rows = append(rows, funcRows(d, t.Funcs)...)
		rows = append(rows, methodRows(d, t)...)
		writeRows(&b, "type "+t.Name, rows)
	}
	writeRows(&b, "Constants and variables", valueRows(d, d.Consts, d.Vars))
	return b.String(), nil
}

// importPath maps a directory to the path a caller writes. The cel module
// has its own go.mod but the same import shape.
func importPath(dir string) string { return dir }

type row struct{ sig, doc string }

func writeRows(b *strings.Builder, heading string, rows []row) {
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(b, "### %s\n\n", heading)
	fmt.Fprintln(b, "| | |")
	fmt.Fprintln(b, "|---|---|")
	for _, r := range rows {
		fmt.Fprintf(b, "| %s | %s |\n", r.sig, r.doc)
	}
	fmt.Fprintln(b)
}

func funcRows(d *doc.Package, fs []*doc.Func) []row {
	out := make([]row, 0, len(fs))
	for _, f := range fs {
		if !ast.IsExported(f.Name) {
			continue
		}
		out = append(out, row{code(oneLine(f.Decl)), first(d, f.Doc)})
	}
	return out
}

func methodRows(d *doc.Package, t *doc.Type) []row {
	out := make([]row, 0, len(t.Methods))
	for _, m := range t.Methods {
		if !ast.IsExported(m.Name) {
			continue
		}
		out = append(out, row{code(oneLine(m.Decl)), first(d, m.Doc)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].sig < out[j].sig })
	return out
}

func valueRows(d *doc.Package, groups ...[]*doc.Value) []row {
	var out []row
	for _, g := range groups {
		for _, v := range g {
			for _, name := range v.Names {
				if !ast.IsExported(name) {
					continue
				}
				out = append(out, row{code(name), first(d, v.Doc)})
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].sig < out[j].sig })
	return out
}

// typeLine renders a type's declaration head: `type Name struct` rather
// than the whole body, which belongs on pkg.go.dev.
func typeLine(t *doc.Type) string {
	switch t.Decl.Specs[0].(*ast.TypeSpec).Type.(type) {
	case *ast.StructType:
		return "type " + t.Name + " struct"
	case *ast.InterfaceType:
		return "type " + t.Name + " interface"
	}
	return "type " + t.Name
}

// oneLine renders a declaration's signature with the body removed.
func oneLine(fn *ast.FuncDecl) string {
	var b strings.Builder
	b.WriteString("func ")
	if fn.Recv != nil && len(fn.Recv.List) > 0 {
		b.WriteString("(" + exprString(fn.Recv.List[0].Type) + ") ")
	}
	b.WriteString(fn.Name.Name)
	b.WriteString(fieldList(fn.Type.TypeParams, "[", "]"))
	b.WriteString(fieldList(fn.Type.Params, "(", ")"))
	if res := fn.Type.Results; res != nil && len(res.List) > 0 {
		out := fieldList(res, "(", ")")
		if len(res.List) == 1 && len(res.List[0].Names) == 0 {
			out = " " + strings.Trim(out, "()")
		} else {
			out = " " + out
		}
		b.WriteString(out)
	}
	return b.String()
}

func fieldList(fl *ast.FieldList, open, close string) string {
	if fl == nil {
		return ""
	}
	parts := make([]string, 0, len(fl.List))
	for _, f := range fl.List {
		names := make([]string, 0, len(f.Names))
		for _, n := range f.Names {
			names = append(names, n.Name)
		}
		typ := exprString(f.Type)
		if len(names) == 0 {
			parts = append(parts, typ)
			continue
		}
		parts = append(parts, strings.Join(names, ", ")+" "+typ)
	}
	return open + strings.Join(parts, ", ") + close
}

// exprString prints a type expression. It handles the shapes that appear
// in signatures; anything else falls back to the node's own string form.
func exprString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + exprString(t.X)
	case *ast.SelectorExpr:
		return exprString(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		return "[]" + exprString(t.Elt)
	case *ast.MapType:
		return "map[" + exprString(t.Key) + "]" + exprString(t.Value)
	case *ast.Ellipsis:
		return "..." + exprString(t.Elt)
	case *ast.InterfaceType:
		if t.Methods == nil || len(t.Methods.List) == 0 {
			return "any"
		}
		return "interface{...}"
	case *ast.FuncType:
		// The results matter: a rule body is func(ctx, T) error, and
		// printing only the parameters would hide what it must return.
		out := "func" + fieldList(t.Params, "(", ")")
		if r := t.Results; r != nil && len(r.List) > 0 {
			res := fieldList(r, "(", ")")
			if len(r.List) == 1 && len(r.List[0].Names) == 0 {
				res = strings.Trim(res, "()")
			}
			out += " " + res
		}
		return out
	case *ast.IndexExpr:
		return exprString(t.X) + "[" + exprString(t.Index) + "]"
	case *ast.IndexListExpr:
		parts := make([]string, 0, len(t.Indices))
		for _, i := range t.Indices {
			parts = append(parts, exprString(i))
		}
		return exprString(t.X) + "[" + strings.Join(parts, ", ") + "]"
	case *ast.ChanType:
		return "chan " + exprString(t.Value)
	}
	return fmt.Sprintf("%T", e)
}

// first is the first sentence of a doc comment, flattened to one line and
// escaped for a table cell.
func first(d *doc.Package, s string) string {
	// Package.Synopsis, not the deprecated package-level function: this
	// one resolves doc links rather than leaving their markup in the text.
	s = strings.TrimSpace(d.Synopsis(s))
	if s == "" {
		return ""
	}
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.Join(strings.Fields(s), " ")
}

func code(s string) string { return "`" + strings.ReplaceAll(s, "|", `\|`) + "`" }
