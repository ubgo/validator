// Builder emits `vb` source equivalent to a migrated schema: one
// `<Type>Schema` variable per struct, written against the generated
// `<Type>Fields` accessors. It is the migration's real deliverable — after
// running it a team deletes the tags and keeps the rules as code the
// compiler checks.
//
// The emitted source is the same shape a person would write; it round-trips
// (building it yields the input IR byte for byte), which the fixture package
// proves at compile time and in its test.

// BuilderHeader marks emitted files as generated.
const BuilderHeader = "// Code generated by validatorctl migrate; DO NOT EDIT — or do: this file is yours now."

// vbImport is the builder package path.
const vbImport = "github.com/ubgo/validator/vb"

// irImport is needed for gate helpers and constants.
const irImport = "github.com/ubgo/validator/ir"

// BuilderOptions configures source emission.
type BuilderOptions struct {
	// Package is the Go package name of the output file.
	Package string

	// Suffix is the accessor variable suffix (`Fields` → UserFields).
	Suffix string
}

// Builder renders the schema as Go source. Types is the migration order
// (root first); defs are emitted before the root so the root can reference
// them.
func Builder(s *ir.Schema, types []string, opts BuilderOptions) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("tags: BuilderOptions.Package is required")
	}
	if opts.Suffix == "" {
		opts.Suffix = "Fields"
	}
	e := &emitter{suffix: opts.Suffix}
	var b bytes.Buffer
	fmt.Fprintln(&b, BuilderHeader)
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	fmt.Fprintf(&b, "import (\n\t%q\n\t%q\n)\n\n", irImport, vbImport)
	fmt.Fprintln(&b, "var _ ir.Kind // ir is referenced by gates; keep the import when a schema has none")
	fmt.Fprintln(&b)

	// Defs first, in dependency-friendly order (the migration recorded them
	// in discovery order, which is reverse-dependency for a tree; reverse
	// it so leaves come first).
	defs := append([]string{}, types[1:]...)
	for i, j := 0, len(defs)-1; i < j; i, j = i+1, j-1 {
		defs[i], defs[j] = defs[j], defs[i]
	}
	for _, name := range defs {
		obj, ok := s.Defs[name].(*ir.ObjectNode)
		if !ok {
			return nil, fmt.Errorf("tags: def %s is not an object", name)
		}
		e.schema(&b, name, obj)
	}
	root, ok := s.Root.(*ir.ObjectNode)
	if !ok {
		return nil, fmt.Errorf("tags: root is not an object")
	}
	e.schema(&b, s.Meta.Title, root)
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("tags: emitted source does not format: %w\n%s", err, b.String())
	}
	return src, nil
}

type emitter struct {
	suffix string
}

func (e *emitter) schema(b *bytes.Buffer, name string, obj *ir.ObjectNode) {
	fmt.Fprintf(b, "// %sSchema is the migrated schema for %s.\n", name, name)
	fmt.Fprintf(b, "var %sSchema = vb.Struct(%q,\n", name, name)
	for i := range obj.Fields {
		f := &obj.Fields[i]
		fmt.Fprintf(b, "\tvb.F(%s%s.%s, %s)", name, e.suffix, f.Name, e.node(f.Type))
		if f.Optional {
			b.WriteString(".Optional()")
		}
		b.WriteString(",\n")
	}
	b.WriteString(")")
	if obj.Extra != "" {
		fmt.Fprintf(b, ".\n\tExtra(%s)", extraConst(obj.Extra))
	}
	if len(obj.Gated) > 0 {
		b.WriteString(".\n\tGate(\n")
		for _, g := range obj.Gated {
			fmt.Fprintf(b, "\t\t%s,\n", e.gate(name, g))
		}
		b.WriteString("\t)")
	}
	b.WriteString(".\n\tMustBuild()\n\n")
}

// node renders a type node as a builder expression.
func (e *emitter) node(n ir.TypeNode) string {
	var out string
	switch t := n.(type) {
	case *ir.StringNode:
		out = "vb.String()" + e.rules(t.Rules)
	case *ir.IntNode:
		out = "vb.Int[" + intGoType(t) + "]()" + e.rules(t.Rules)
	case *ir.FloatNode:
		ty := "float64"
		if t.Bits == 32 {
			ty = "float32"
		}
		out = "vb.Float[" + ty + "]()" + e.rules(t.Rules)
	case *ir.BoolNode:
		out = "vb.Bool()" + e.rules(t.Rules)
	case *ir.BytesNode:
		out = "vb.Bytes()" + e.rules(t.Rules)
	case *ir.TimeNode:
		out = "vb.Time()" + e.rules(t.Rules)
	case *ir.DurationNode:
		out = "vb.Duration()" + e.rules(t.Rules)
	case *ir.ArrayNode:
		out = "vb.Array(" + e.node(t.Elem) + ")" + e.rules(t.Rules)
	case *ir.MapNode:
		out = "vb.Map(" + e.node(t.Key) + ", " + e.node(t.Val) + ")" + e.rules(t.Rules)
	case *ir.RefNode:
		out = "vb.Ref(" + t.Ref + "Schema)"
	case *ir.AnyNode:
		out = "vb.Any[any]()"
	default:
		out = "vb.Any[any]() /* " + string(n.Kind()) + " is not emitted by migrate */"
	}
	if nullableOf(n) {
		out = "vb.Ptr(" + out + ")"
	}
	return out
}

// rules renders rule method calls.
func (e *emitter) rules(rs []ir.Rule) string {
	var b strings.Builder
	for _, r := range rs {
		switch r.Kind {
		case ir.RuleMinLength:
			fmt.Fprintf(&b, ".MinLength(%s)", intLit(r.Params[ir.ParamValue]))
		case ir.RuleMaxLength:
			fmt.Fprintf(&b, ".MaxLength(%s)", intLit(r.Params[ir.ParamValue]))
		case ir.RuleMinItems:
			fmt.Fprintf(&b, ".MinItems(%s)", intLit(r.Params[ir.ParamValue]))
		case ir.RuleMaxItems:
			fmt.Fprintf(&b, ".MaxItems(%s)", intLit(r.Params[ir.ParamValue]))
		case ir.RuleUnique:
			b.WriteString(".Unique()")
		case ir.RuleMin, ir.RuleMax, ir.RuleGt, ir.RuleGte, ir.RuleLt, ir.RuleLte, ir.RuleMultipleOf:
			fmt.Fprintf(&b, ".%s(%s)", strings.ToUpper(string(r.Kind[:1]))+string(r.Kind[1:]), numLit(r.Params[ir.ParamValue]))
		case ir.RulePattern:
			fmt.Fprintf(&b, ".Pattern(%s)", strconv.Quote(fmt.Sprint(r.Params[ir.ParamRegex])))
		case ir.RuleEnum:
			values, _ := r.Params[ir.ParamValues].([]any)
			parts := make([]string, len(values))
			for i, v := range values {
				parts[i] = anyLit(v)
			}
			fmt.Fprintf(&b, ".Enum(%s)", strings.Join(parts, ", "))
		case ir.RuleConst:
			fmt.Fprintf(&b, ".Const(%s)", anyLit(r.Params[ir.ParamValue]))
		case ir.RuleEmail:
			b.WriteString(".Email()")
		case ir.RuleURL:
			b.WriteString(".URL()")
		case ir.RuleUUID:
			b.WriteString(".UUID()")
		case ir.RuleULID:
			b.WriteString(".ULID()")
		case ir.RuleIPv4:
			b.WriteString(".IPv4()")
		case ir.RuleIPv6:
			b.WriteString(".IPv6()")
		case ir.RuleIP:
			b.WriteString(".IP()")
		case ir.RuleCIDR:
			b.WriteString(".CIDR()")
		case ir.RuleMAC:
			b.WriteString(".MAC()")
		case ir.RuleHostname:
			b.WriteString(".Hostname()")
		case ir.RuleBase64:
			b.WriteString(".Base64()")
		case ir.RuleJSON:
			b.WriteString(".JSON()")
		case ir.RuleSemver:
			b.WriteString(".Semver()")
		case ir.RuleDate:
			b.WriteString(".Date()")
		case ir.RuleDateTime:
			b.WriteString(".DateTime()")
		case ir.RuleNotBlank:
			b.WriteString(".NotBlank()")
		case ir.RuleCreditCard:
			b.WriteString(".CreditCard()")
		case ir.RuleJWT:
			b.WriteString(".JWT()")
		case ir.RuleCountryCode:
			b.WriteString(".CountryCode()")
		case ir.RuleCurrencyCode:
			b.WriteString(".CurrencyCode()")
		case ir.RuleHexColor:
			b.WriteString(".HexColor()")
		case ir.RuleE164:
			b.WriteString(".E164()")
		case ir.RuleLatitude:
			b.WriteString(".Latitude()")
		case ir.RuleLongitude:
			b.WriteString(".Longitude()")
		case ir.RuleAfter:
			fmt.Fprintf(&b, ".With(vb.AfterField(%q))", r.Params[ir.ParamField])
		case ir.RuleBefore:
			fmt.Fprintf(&b, ".With(vb.BeforeField(%q))", r.Params[ir.ParamField])
		}
	}
	return b.String()
}

// gate renders an object-level gate through the ir constructors, naming
// fields by the accessor so a rename stays a compile error.
func (e *emitter) gate(typeName string, g ir.GatedRules) string {
	acc := func(field string) string { return typeName + e.suffix + "." + field }
	switch g.Kind {
	case ir.GateRequires:
		fields := make([]string, len(g.Fields))
		for i, f := range g.Fields {
			fields[i] = acc(f)
		}
		return fmt.Sprintf("vb.Requires(%s, %s)", e.cond(g.Cond), strings.Join(fields, ", "))
	case ir.GateGroup:
		fields := make([]string, len(g.Fields))
		for i, f := range g.Fields {
			fields[i] = acc(f)
		}
		return fmt.Sprintf("vb.Group(%s, %s)", groupConst(g.Mode), strings.Join(fields, ", "))
	}
	return "/* when-gates are not produced by migrate */ ir.GatedRules{}"
}

// cond renders a condition through the string-keyed ir constructors; the
// builder's typed helpers need FieldRefs of matching types, which a
// migration cannot know without the type checker.
func (e *emitter) cond(c *ir.Condition) string {
	if c == nil {
		return "ir.Condition{}"
	}
	switch c.Kind {
	case ir.CondCmp:
		return fmt.Sprintf("ir.Cmp(%q, ir.%s, %s)", c.Field, opConst(ir.CmpOp(c.Op)), anyLit(c.Value))
	case ir.CondPresence:
		op := "ir.Present"
		if ir.PresenceOp(c.Op) == ir.Absent {
			op = "ir.Absent"
		}
		return fmt.Sprintf("ir.HasField(%q, %s)", c.Field, op)
	case ir.CondAnd, ir.CondOr:
		parts := make([]string, len(c.Sub))
		for i := range c.Sub {
			parts[i] = e.cond(&c.Sub[i])
		}
		fn := "ir.And"
		if c.Kind == ir.CondOr {
			fn = "ir.Or"
		}
		return fn + "(" + strings.Join(parts, ", ") + ")"
	case ir.CondNot:
		return "ir.Not(" + e.cond(&c.Sub[0]) + ")"
	}
	return "ir.Condition{}"
}

func opConst(op ir.CmpOp) string {
	switch op {
	case ir.OpEq:
		return "OpEq"
	case ir.OpNe:
		return "OpNe"
	case ir.OpGt:
		return "OpGt"
	case ir.OpGte:
		return "OpGte"
	case ir.OpLt:
		return "OpLt"
	}
	return "OpLte"
}

func groupConst(m ir.GroupMode) string {
	switch m {
	case ir.ExactlyOne:
		return "ir.ExactlyOne"
	case ir.AtLeastOne:
		return "ir.AtLeastOne"
	}
	return "ir.AllOrNone"
}

func extraConst(p ir.ExtraPolicy) string {
	switch p {
	case ir.ExtraForbid:
		return "ir.ExtraForbid"
	case ir.ExtraAllow:
		return "ir.ExtraAllow"
	}
	return "ir.ExtraIgnore"
}

func intGoType(t *ir.IntNode) string {
	prefix := "int"
	if t.Unsigned {
		prefix = "uint"
	}
	if t.Bits == 0 {
		return prefix
	}
	return prefix + strconv.Itoa(t.Bits)
}

func intLit(v any) string {
	switch x := v.(type) {
	case int:
		return strconv.Itoa(x)
	case float64:
		return strconv.Itoa(int(x))
	}
	return fmt.Sprint(v)
}

func numLit(v any) string {
	switch x := v.(type) {
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	}
	return fmt.Sprint(v)
}

func anyLit(v any) string {
	switch x := v.(type) {
	case string:
		return strconv.Quote(x)
	case bool:
		return strconv.FormatBool(x)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	}
	return fmt.Sprint(v)
}

func nullableOf(n ir.TypeNode) bool {
	switch t := n.(type) {
	case *ir.ObjectNode:
		return t.Nullable
	case *ir.StringNode:
		return t.Nullable
	case *ir.IntNode:
		return t.Nullable
	case *ir.FloatNode:
		return t.Nullable
	case *ir.BoolNode:
		return t.Nullable
	case *ir.BytesNode:
		return t.Nullable
	case *ir.TimeNode:
		return t.Nullable
	case *ir.DurationNode:
		return t.Nullable
	case *ir.ArrayNode:
		return t.Nullable
	case *ir.MapNode:
		return t.Nullable
	case *ir.RefNode:
		return t.Nullable
	case *ir.AnyNode:
		return t.Nullable
	}
	return false
}

// sortedKeys returns map keys in lexical order.
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
