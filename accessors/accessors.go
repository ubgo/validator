// Package accessors generates typed field accessors — the recommended
// authoring surface (docsi/MISSION.md ADR-VAL-006).
//
// For every struct in a package it emits a `<Type>Fields` value whose
// members are [vb.FieldRef]s: one per exported field, carrying the Go
// name, the json wire name, and a getter. Authors then write rules against
// `UserFields.Email` instead of the string "Email": the field name
// autocompletes, and renaming the struct field makes stale rules a compile
// error after regeneration. Generated accessors live in their own file
// (`*.gen.go`) so re-running the generator never touches hand-written
// rules — the ent/sqlc split.
//
// The generator works from source (go/parser), not from a compiled
// package, so it needs no build and no type checker: field types are
// copied verbatim from the declaration, and the imports those types need
// are carried over from the declaring file. That is also its limit — it
// does not resolve type aliases or dot-imports, and it skips generic
// structs and embedded fields (both documented in the output as comments,
// never silently).
package accessors

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

// DefaultOutput is the file name written when none is given. One file per
// package keeps `go generate` idempotent and the diff reviewable.
const DefaultOutput = "fields.gen.go"

// DefaultSuffix is appended to the type name for the accessor variable.
const DefaultSuffix = "Fields"

// Header is the first line of every generated file; the exact phrase is
// what `go vet` and tooling look for to recognise generated code.
const Header = "// Code generated by validatorctl fields; DO NOT EDIT."

// vbImport is the builder package the accessors are typed with.
const vbImport = "github.com/ubgo/validator/vb"

// Options configures a generation.
type Options struct {
	// Dir is the package directory to scan. Required.
	Dir string

	// Types restricts generation to these struct names. Empty means every
	// struct in the package.
	Types []string

	// Output is the file name (inside Dir) to write. Default [DefaultOutput].
	Output string

	// Suffix is appended to the type name for the accessor variable.
	// Default [DefaultSuffix].
	Suffix string

	// IncludeUnexported also emits accessors for unexported fields. Off by
	// default: the generated file sits in the same package so it compiles
	// either way, but exposing unexported fields through an exported
	// accessor variable is usually not what an author intends.
	IncludeUnexported bool
}

// Result is a completed generation.
type Result struct {
	// Path is the output file's absolute path.
	Path string

	// Source is the formatted Go source that was (or would be) written.
	Source []byte

	// Types lists the struct names that received accessors, in order.
	Types []string

	// Skipped explains every struct or field the generator could not
	// handle, so nothing disappears silently.
	Skipped []string
}

// Generate scans the package and returns the generated source without
// writing it. Use [Write] to persist.
func Generate(opts Options) (*Result, error) {
	if opts.Dir == "" {
		return nil, errors.New("accessors: Dir is required")
	}
	if opts.Output == "" {
		opts.Output = DefaultOutput
	}
	if opts.Suffix == "" {
		opts.Suffix = DefaultSuffix
	}
	fset := token.NewFileSet()
	pkg, err := parsePackage(fset, opts.Dir, opts.Output)
	if err != nil {
		return nil, err
	}
	g := &generator{fset: fset, opts: opts, pkg: pkg, imports: map[string]string{}}
	if err := g.collect(); err != nil {
		return nil, err
	}
	src, err := g.render()
	if err != nil {
		return nil, err
	}
	abs, err := filepath.Abs(filepath.Join(opts.Dir, opts.Output))
	if err != nil {
		return nil, err
	}
	return &Result{Path: abs, Source: src, Types: g.typeNames(), Skipped: g.skipped}, nil
}

// Write generates and writes the file, returning the result. The write is
// skipped when the content is unchanged so `go generate` leaves mtimes
// alone.
func Write(opts Options) (*Result, error) {
	res, err := Generate(opts)
	if err != nil {
		return nil, err
	}
	if existing, err := os.ReadFile(res.Path); err == nil && bytes.Equal(existing, res.Source) {
		return res, nil
	}
	if err := os.WriteFile(res.Path, res.Source, 0o644); err != nil {
		return nil, fmt.Errorf("accessors: write %s: %w", res.Path, err)
	}
	return res, nil
}

// Package is the parsed, non-test, non-generated source of one package
// directory. A small stand-in for the deprecated ast.Package: the
// generators need file ASTs, a package name and struct declarations,
// nothing the type checker provides. Shared with the codegen package.
type Package struct {
	fset  *token.FileSet
	name  string
	files map[string]*ast.File
}

// Name returns the package name.
func (p *Package) Name() string { return p.name }

// StructDecl is a struct type declaration with the import map of the file
// that declares it, so field type expressions can be reproduced with the
// imports they need.
type StructDecl struct {
	Name    string
	Type    *ast.StructType
	Imports map[string]string
}

// Struct looks a struct declaration up by name.
func (p *Package) Struct(name string) (*StructDecl, bool) {
	for _, file := range p.files {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				st, isStruct := ts.Type.(*ast.StructType)
				if isStruct && ts.Name.Name == name {
					return &StructDecl{Name: name, Type: st, Imports: importMap(file)}, true
				}
			}
		}
	}
	return nil, false
}

// TypeString prints a type expression as it appeared in source.
func (p *Package) TypeString(e ast.Expr) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, p.fset, e)
	return buf.String()
}

// ParsePackage reads every buildable source file in dir, skipping tests,
// `*.gen.go` files and the named output, and rejects a directory that
// holds more than one package name.
func ParsePackage(dir, output string) (*Package, error) {
	return parsePackage(token.NewFileSet(), dir, output)
}

func parsePackage(fset *token.FileSet, dir, output string) (*Package, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("accessors: read %s: %w", dir, err)
	}
	pkg := &Package{fset: fset, files: map[string]*ast.File{}}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".gen.go") || name == output {
			continue
		}
		path := filepath.Join(dir, name)
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("accessors: parse %s: %w", path, err)
		}
		if pkg.name != "" && file.Name.Name != pkg.name {
			return nil, fmt.Errorf("accessors: directory holds several packages: %s, %s", pkg.name, file.Name.Name)
		}
		pkg.name = file.Name.Name
		pkg.files[name] = file
	}
	if pkg.name == "" {
		return nil, errors.New("accessors: no Go package found")
	}
	return pkg, nil
}

// structInfo is one struct to emit.
type structInfo struct {
	name   string
	fields []fieldInfo
}

// fieldInfo is one accessor.
type fieldInfo struct {
	name     string
	jsonName string
	typeExpr string
}

// generator accumulates what render needs.
type generator struct {
	fset    *token.FileSet
	opts    Options
	pkg     *Package
	structs []structInfo
	skipped []string

	// imports maps package identifier → import path for every selector the
	// emitted field types reference.
	imports map[string]string
}

// collect walks every file's type declarations.
func (g *generator) collect() error {
	wanted := map[string]bool{}
	for _, t := range g.opts.Types {
		wanted[t] = true
	}
	files := make([]string, 0, len(g.pkg.files))
	for name := range g.pkg.files {
		files = append(files, name)
	}
	sort.Strings(files)
	for _, fname := range files {
		file := g.pkg.files[fname]
		fileImports := importMap(file)
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				st, isStruct := ts.Type.(*ast.StructType)
				if !isStruct {
					continue
				}
				if len(wanted) > 0 && !wanted[ts.Name.Name] {
					continue
				}
				if ts.TypeParams != nil && len(ts.TypeParams.List) > 0 {
					g.skipped = append(g.skipped, fmt.Sprintf("%s: generic struct (type parameters are not supported)", ts.Name.Name))
					continue
				}
				g.structs = append(g.structs, g.structOf(ts.Name.Name, st, fileImports))
				delete(wanted, ts.Name.Name)
			}
		}
	}
	if len(wanted) > 0 {
		missing := make([]string, 0, len(wanted))
		for n := range wanted {
			missing = append(missing, n)
		}
		sort.Strings(missing)
		return fmt.Errorf("accessors: struct(s) not found in package: %s", strings.Join(missing, ", "))
	}
	if len(g.structs) == 0 {
		return errors.New("accessors: no structs to generate")
	}
	return nil
}

// structOf extracts the emittable fields of one struct.
func (g *generator) structOf(name string, st *ast.StructType, fileImports map[string]string) structInfo {
	info := structInfo{name: name}
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			g.skipped = append(g.skipped, fmt.Sprintf("%s: embedded field %s (promote its fields explicitly)", name, g.exprString(f.Type)))
			continue
		}
		typeExpr := g.exprString(f.Type)
		g.noteImports(f.Type, fileImports)
		for _, id := range f.Names {
			if id.Name == "_" {
				continue
			}
			if !g.opts.IncludeUnexported && !id.IsExported() {
				g.skipped = append(g.skipped, fmt.Sprintf("%s.%s: unexported field (use --unexported to include)", name, id.Name))
				continue
			}
			info.fields = append(info.fields, fieldInfo{name: id.Name, jsonName: jsonName(f.Tag, id.Name), typeExpr: typeExpr})
		}
	}
	return info
}

// exprString prints a type expression as it appeared in source.
func (g *generator) exprString(e ast.Expr) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, g.fset, e)
	return buf.String()
}

// noteImports records the imports a type expression depends on by finding
// every `pkg.Name` selector inside it.
func (g *generator) noteImports(e ast.Expr, fileImports map[string]string) {
	ast.Inspect(e, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if id, isIdent := sel.X.(*ast.Ident); isIdent {
			if path, known := fileImports[id.Name]; known {
				g.imports[id.Name] = path
			}
		}
		return true
	})
}

// importMap builds identifier → path for a file's imports. The identifier
// is the explicit alias when present, otherwise the last path segment
// (the common case; a package whose name differs from its directory is
// the documented limitation).
func importMap(file *ast.File) map[string]string {
	out := map[string]string{}
	for _, imp := range file.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			continue
		}
		name := filepath.Base(path)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if name == "." || name == "_" {
			continue
		}
		out[name] = path
	}
	return out
}

// jsonName reads the json tag's name, or "" when absent, "-", or equal to
// the Go name (no wire override needed).
func jsonName(tag *ast.BasicLit, goName string) string {
	if tag == nil {
		return ""
	}
	raw, err := strconv.Unquote(tag.Value)
	if err != nil {
		return ""
	}
	name, _, _ := strings.Cut(reflect.StructTag(raw).Get("json"), ",")
	if name == "" || name == "-" || name == goName {
		return ""
	}
	return name
}

func (g *generator) typeNames() []string {
	out := make([]string, 0, len(g.structs))
	for _, s := range g.structs {
		out = append(out, s.name)
	}
	return out
}

// render writes the Go source and gofmt-formats it. The template is a
// plain writer rather than text/template so the output shape is visible
// in one place and every emitted token is a Go identifier or a quoted
// string — nothing user-controlled is interpolated raw.
func (g *generator) render() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintln(&b, Header)
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "package %s\n\n", g.pkg.name)

	paths := make([]string, 0, len(g.imports)+1)
	seen := map[string]bool{}
	for _, p := range g.imports {
		if !seen[p] {
			seen[p] = true
			paths = append(paths, p)
		}
	}
	if !seen[vbImport] {
		paths = append(paths, vbImport)
	}
	sort.Strings(paths)
	fmt.Fprintln(&b, "import (")
	for _, p := range paths {
		alias := ""
		for id, path := range g.imports {
			if path == p && id != filepath.Base(p) {
				alias = id + " "
			}
		}
		fmt.Fprintf(&b, "\t%s%s\n", alias, strconv.Quote(p))
	}
	fmt.Fprintln(&b, ")")

	for _, s := range g.skipped {
		fmt.Fprintf(&b, "\n// skipped: %s\n", s)
	}

	for _, s := range g.structs {
		varName := s.name + g.opts.Suffix
		fmt.Fprintf(&b, "\n// %s names every field of %s for rule authoring.\n", varName, s.name)
		fmt.Fprintf(&b, "// Use with vb.F: vb.F(%s.<Field>, vb.<Builder>()).\n", varName)
		fmt.Fprintf(&b, "var %s = struct {\n", varName)
		for _, f := range s.fields {
			fmt.Fprintf(&b, "\t%s vb.FieldRef[%s, %s]\n", f.name, s.name, f.typeExpr)
		}
		fmt.Fprintln(&b, "}{")
		for _, f := range s.fields {
			fmt.Fprintf(&b, "\t%s: vb.NewField(%s, func(v %s) %s { return v.%s })", f.name, strconv.Quote(f.name), s.name, f.typeExpr, f.name)
			if f.jsonName != "" {
				fmt.Fprintf(&b, ".JSON(%s)", strconv.Quote(f.jsonName))
			}
			fmt.Fprintln(&b, ",")
		}
		fmt.Fprintln(&b, "}")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		// A formatting failure means the generator emitted invalid Go —
		// return the raw text in the error so the bug is visible.
		return nil, fmt.Errorf("accessors: generated source does not format: %w\n%s", err, b.String())
	}
	return src, nil
}
