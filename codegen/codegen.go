// stopCheck emits the fail-fast early return, outside probes only: inside a
// union probe a `return` would abandon the remaining variants, and the
// probe list is fail-fast anyway so no work is wasted there.
func (g *gen) stopCheck() {
	if g.inProbe > 0 {
		return
	}
	g.w("\tif errs.Stopped() {")
	g.w("\t\treturn")
	g.w("\t}")
}
