// Package codegen emits specialized validation functions from the IR — the
// production executor (docsi/MISSION.md ADR-VAL-003).
//
// For a schema whose root and defs name Go structs in a package, it writes
// `Validate<Type>(ctx, *Type, rt.Registry) *verr.Errors` functions in which
// every field access, presence test and rule is a direct Go expression: no
// reflection, no map lookups, no allocation on the success path. The
// semantics are the interpreter's — the two are conformance-tested against
// each other on the same inputs — and the shared pieces (formats,
// uniqueness, normalized equality, comparison) are literally the same code
// via codegen/rt.
//
// Like the accessor generator it reads Go types from source (go/parser),
// which is what lets it know a field is `*string` versus `string` and emit
// the right presence test and dereference. What it cannot do yet is
// refused at generation time, never emitted as a no-op: unions, discriminated
// unions, value transforms, and CEL conditions. Those schemas run under the
// interpreter until codegen catches up (docsi/TASKS.md phase-4).
package codegen

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/ubgo/validator/accessors"
	"github.com/ubgo/validator/internal/rules"
	"github.com/ubgo/validator/ir"
)

// DefaultOutput is the file written when none is given.
const DefaultOutput = "validate.gen.go"

// Header marks the file as generated for tooling.
const Header = "// Code generated by validatorctl gen; DO NOT EDIT."

// FuncPrefix is prepended to the type name for the exported entry point.
const FuncPrefix = "Validate"

// Import paths the generated file needs.
const (
	rtImport   = "github.com/ubgo/validator/codegen/rt"
	irImport   = "github.com/ubgo/validator/ir"
	verrImport = "github.com/ubgo/validator/verr"
)

// Options configures a generation.
type Options struct {
	// Schema is the IR to compile. Its root title and every def name must
	// be struct types declared in Dir.
	Schema *ir.Schema

	// Dir is the package directory holding those structs. Required.
	Dir string

	// Output is the file name (inside Dir) to write. Default [DefaultOutput].
	Output string
}

// Result is a completed generation.
type Result struct {
	Path   string
	Source []byte
	// Funcs lists the exported validators emitted, in order.
	Funcs []string
}

// Generate produces the source without writing it.
func Generate(opts Options) (*Result, error) {
	if opts.Schema == nil {
		return nil, errors.New("codegen: Schema is required")
	}
	if opts.Dir == "" {
		return nil, errors.New("codegen: Dir is required")
	}
	if opts.Output == "" {
		opts.Output = DefaultOutput
	}
	if err := ir.Check(opts.Schema); err != nil {
		return nil, err
	}
	pkg, err := accessors.ParsePackage(opts.Dir, opts.Output)
	if err != nil {
		return nil, fmt.Errorf("codegen: %w", err)
	}
	g := &gen{opts: opts, pkg: pkg, imports: map[string]string{}, regexps: map[string]string{}, hoisted: map[string]string{}}
	if err := g.run(); err != nil {
		return nil, err
	}
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("codegen: generated source does not format: %w\n%s", err, g.buf.String())
	}
	abs, err := filepath.Abs(filepath.Join(opts.Dir, opts.Output))
	if err != nil {
		return nil, err
	}
	return &Result{Path: abs, Source: src, Funcs: g.funcs}, nil
}

// Write generates and writes the file, skipping the write when unchanged.
func Write(opts Options) (*Result, error) {
	res, err := Generate(opts)
	if err != nil {
		return nil, err
	}
	if existing, err := os.ReadFile(res.Path); err == nil && bytes.Equal(existing, res.Source) {
		return res, nil
	}
	if err := os.WriteFile(res.Path, res.Source, 0o644); err != nil {
		return nil, fmt.Errorf("codegen: write %s: %w", res.Path, err)
	}
	return res, nil
}

// gen holds generation state.
type gen struct {
	opts    Options
	pkg     *accessors.Package
	buf     bytes.Buffer
	body    bytes.Buffer
	imports map[string]string // identifier → path, from field types
	funcs   []string
	seq     int
	errs    []error
	inProbe int

	// regexps maps pattern → package-level variable name so each pattern is
	// compiled once at init, not once per validation call.
	regexps    map[string]string
	regexOrder []string

	// hoisted maps a literal expression (an enum slice) → package-level var
	// name, so per-call slice literals become one-time initializations.
	hoisted    map[string]string
	hoistOrder []string

	// fallbacks are the embedded IR subtrees handed to the interpreter.
	fallbacks []fallback
}

// fallback is one interpreter-delegated subtree.
type fallback struct {
	name string
	doc  string
	why  string
}

func (g *gen) errf(format string, args ...any) {
	g.errs = append(g.errs, fmt.Errorf("codegen: "+format, args...))
}

// fresh returns a unique local identifier so nested blocks never shadow.
func (g *gen) fresh(prefix string) string {
	g.seq++
	return prefix + strconv.Itoa(g.seq)
}

func (g *gen) w(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
	g.body.WriteByte('\n')
}

// run emits one validator per named struct (root + defs) into body, then
// assembles the file with the imports the body turned out to need.
func (g *gen) run() error {
	root := g.opts.Schema.Meta.Title
	if root == "" {
		return errors.New("codegen: schema has no title; the root must name a Go struct")
	}
	rootObj, ok := g.opts.Schema.Root.(*ir.ObjectNode)
	if !ok {
		return errors.New("codegen: root must be an object")
	}
	g.emitValidator(root, rootObj)
	names := make([]string, 0, len(g.opts.Schema.Defs))
	for n := range g.opts.Schema.Defs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		obj, ok := g.opts.Schema.Defs[n].(*ir.ObjectNode)
		if !ok {
			g.errf("def %s is not an object; only struct defs can be compiled", n)
			continue
		}
		g.emitValidator(n, obj)
	}
	if err := errors.Join(g.errs...); err != nil {
		return err
	}

	fmt.Fprintln(&g.buf, Header)
	fmt.Fprintln(&g.buf)
	fmt.Fprintf(&g.buf, "package %s\n\n", g.pkg.Name())
	paths := map[string]string{"context": "", rtImport: "", irImport: "", verrImport: ""}
	for id, p := range g.imports {
		alias := ""
		if id != filepath.Base(p) {
			alias = id
		}
		paths[p] = alias
	}
	sorted := make([]string, 0, len(paths))
	for p := range paths {
		sorted = append(sorted, p)
	}
	sort.Strings(sorted)
	fmt.Fprintln(&g.buf, "import (")
	for _, p := range sorted {
		if alias := paths[p]; alias != "" {
			fmt.Fprintf(&g.buf, "\t%s %s\n", alias, strconv.Quote(p))
		} else {
			fmt.Fprintf(&g.buf, "\t%s\n", strconv.Quote(p))
		}
	}
	fmt.Fprintln(&g.buf, ")")
	fmt.Fprintln(&g.buf)
	// Silence unused-import errors for helpers a particular schema does not
	// reach; the references cost nothing.
	fmt.Fprintln(&g.buf, "var (")
	fmt.Fprintln(&g.buf, "\t_ = rt.Present")
	fmt.Fprintln(&g.buf, "\t_ ir.CmpOp")
	fmt.Fprintln(&g.buf, ")")
	if len(g.hoistOrder) > 0 {
		fmt.Fprintln(&g.buf)
		fmt.Fprintln(&g.buf, "// Literal operands built once, not per validation call.")
		fmt.Fprintln(&g.buf, "var (")
		for _, lit := range g.hoistOrder {
			fmt.Fprintf(&g.buf, "\t%s = %s\n", g.hoisted[lit], lit)
		}
		fmt.Fprintln(&g.buf, ")")
	}
	if len(g.fallbacks) > 0 {
		fmt.Fprintln(&g.buf)
		fmt.Fprintln(&g.buf, "// Subtrees the generator hands to the interpreter, parsed once at init.")
		fmt.Fprintln(&g.buf, "// Each is listed with the reason; the value is validated at the same path")
		fmt.Fprintln(&g.buf, "// with the same issues a full interpreter run would produce.")
		fmt.Fprintln(&g.buf, "var (")
		for _, fb := range g.fallbacks {
			fmt.Fprintf(&g.buf, "\t// %s\n", fb.why)
			fmt.Fprintf(&g.buf, "\t%s = rt.MustSchema(%s)\n", fb.name, strconv.Quote(fb.doc))
		}
		fmt.Fprintln(&g.buf, ")")
	}
	if len(g.regexOrder) > 0 {
		fmt.Fprintln(&g.buf)
		fmt.Fprintln(&g.buf, "// Patterns are compiled once at package init; ir.Check already proved")
		fmt.Fprintln(&g.buf, "// they parse, so MustCompile cannot panic here.")
		fmt.Fprintln(&g.buf, "var (")
		for _, re := range g.regexOrder {
			fmt.Fprintf(&g.buf, "\t%s = regexp.MustCompile(%s)\n", g.regexps[re], strconv.Quote(re))
		}
		fmt.Fprintln(&g.buf, ")")
	}
	g.buf.Write(g.body.Bytes())
	return nil
}

// field is a Go struct field the IR refers to.
type field struct {
	name     string
	goType   string
	decl     *accessors.StructDecl
	typeExpr ast.Expr
}

var _ = ast.Inspect // ast stays imported for typeExpr

// structFields indexes a struct's fields by Go name and records the
// imports their types need.
func (g *gen) structFields(typeName string) (map[string]field, bool) {
	decl, ok := g.pkg.Struct(typeName)
	if !ok {
		return nil, false
	}
	out := map[string]field{}
	for _, f := range decl.Type.Fields.List {
		ts := g.pkg.TypeString(f.Type)
		for _, id := range f.Names {
			out[id.Name] = field{name: id.Name, goType: ts, decl: decl, typeExpr: f.Type}
		}
	}
	return out, true
}

// noteTypeImports records the imports a type expression the generated
// code SPELLS OUT needs (only `var x T` for gated pointer fields does).
// Imports are recorded lazily so the file never imports a package it does
// not use — Go would refuse to compile it.
func (g *gen) noteTypeImports(typeExpr string, fileImports map[string]string) {
	for id, path := range fileImports {
		if strings.Contains(typeExpr, id+".") {
			g.imports[id] = path
		}
	}
}

// emitValidator writes the exported entry point and the worker for one
// struct type.
func (g *gen) emitValidator(typeName string, obj *ir.ObjectNode) {
	fields, ok := g.structFields(typeName)
	if !ok {
		g.errf("struct %s not found in %s", typeName, g.opts.Dir)
		return
	}
	fn := FuncPrefix + typeName
	g.funcs = append(g.funcs, fn)
	g.w("// %s validates v against the %s schema. Generated; the semantics are", fn, typeName)
	g.w("// the interpreter's, without reflection.")
	g.w("func %s(ctx context.Context, v *%s, reg rt.Registry) *verr.Errors {", fn, typeName)
	g.w("\terrs := &verr.Errors{}")
	g.w("\t%sInto(ctx, v, reg, errs)", fn)
	g.w("\treturn errs")
	g.w("}")
	g.w("")
	g.w("// %sInto validates into a caller-owned issue list: set errs.FailFast to", fn)
	g.w("// stop at the first issue, or share one list across several schemas.")
	g.w("func %sInto(ctx context.Context, v *%s, reg rt.Registry, errs *verr.Errors) {", fn, typeName)
	g.w("\tif v == nil {")
	g.w("\t\trt.Null(errs, %q)", "$")
	g.w("\t\treturn")
	g.w("\t}")
	g.w("\tvalidate%s(ctx, v, reg, rt.Path{}, errs)", typeName)
	g.w("}")
	g.w("")
	g.w("func validate%s(ctx context.Context, v *%s, reg rt.Registry, path rt.Path, errs *verr.Errors) {", typeName, typeName)
	g.w("\t_, _, _ = ctx, reg, path")
	g.emitObjectBody(obj, "v", fields, "path")
	g.w("}")
	g.w("")
}

// emitObjectBody emits field checks and gates for an object whose value is
// reachable through pointer expression pv.
func (g *gen) emitObjectBody(obj *ir.ObjectNode, pv string, fields map[string]field, pathVar string) {
	for i := range obj.Fields {
		f := &obj.Fields[i]
		gf, ok := fields[f.Name]
		if !ok {
			g.errf("field %s is not declared on the Go struct", f.Name)
			continue
		}
		p := g.fresh("p")
		g.w("\t{")
		g.w("\t\t%s := %s.Field(%q)", p, pathVar, "."+wireName(f))
		g.w("\t\t_ = %s", p)
		expr := pv + "." + f.Name
		present := presenceExpr(expr, gf.goType)
		// Default fills an absent field before the presence test, exactly as
		// the interpreter does; the other pre-transforms rewrite a present
		// string in place (the value is reached through a pointer, so the
		// write-back the interpreter does for pointer input always applies).
		if def, ok := defaultOf(f); ok {
			if lit, ok := typedLiteral(def, gf.goType); ok {
				g.w("\t\tif !(%s) {", present)
				g.w("\t\t\t%s = %s", expr, lit)
				g.w("\t\t}")
			} else {
				g.errf("field %s: default %#v cannot be assigned to %s", f.Name, def, gf.goType)
			}
		}
		g.w("\t\tif !(%s) {", present)
		if !f.Optional {
			g.w("\t\t\trt.Required(errs, %s.String())", p)
		}
		g.w("\t\t} else {")
		g.emitTransforms(f, expr, gf.goType)
		g.emitNode(f.Type, expr, gf.goType, p, pv, fields, true)
		g.w("\t\t}")
		g.w("\t}")
		g.stopCheck()
	}
	for _, gate := range obj.Gated {
		g.emitGate(obj, gate, pv, fields, pathVar)
		g.stopCheck()
	}
}

// emitTransforms applies the pre-phase string transforms in place. Only
// string-typed fields (or pointers to them) are transformed, matching the
// interpreter; unsupported kinds are refused at generation time.
func (g *gen) emitTransforms(f *ir.FieldNode, expr, goType string) {
	for _, t := range f.Transforms {
		if t.Kind == ir.TransformCoerce {
			// Coercion turns strings into typed values on map input; a
			// generated validator only ever sees the typed struct, where the
			// field already has its type. Nothing to do, on purpose.
			g.w("\t\t// coerce: no-op on typed input")
		}
	}
	target := expr
	if goType == "*string" {
		target = "(*" + expr + ")"
	} else if goType != "string" {
		// The interpreter leaves non-strings alone (coerce has no work on
		// typed input); so do we.
		return
	}
	for _, t := range f.Transforms {
		switch t.Kind {
		case ir.TransformTrim:
			g.w("\t\t%s = rt.Trim(%s)", target, target)
		case ir.TransformLower:
			g.w("\t\t%s = rt.Lower(%s)", target, target)
		case ir.TransformUpper:
			g.w("\t\t%s = rt.Upper(%s)", target, target)
		case ir.TransformNormalizeEmail:
			g.w("\t\t%s = rt.NormalizeEmail(%s)", target, target)
		case ir.TransformDefault:
			// Applied before the presence test.
		case ir.TransformCoerce:
			// Noted above, before the string guard.
		default:
			g.errf("field %s: transform %q is not supported by codegen", f.Name, t.Kind)
		}
	}
}

// defaultOf returns the field's default transform value, if declared.
func defaultOf(f *ir.FieldNode) (any, bool) {
	for _, t := range f.Transforms {
		if t.Kind == ir.TransformDefault {
			v, ok := t.Params[ir.ParamValue]
			return v, ok
		}
	}
	return nil, false
}

// typedLiteral renders a default value as an expression assignable to the
// field's Go type.
func typedLiteral(v any, goType string) (string, bool) {
	switch x := v.(type) {
	case string:
		if goType == "string" {
			return strconv.Quote(x), true
		}
		if goType == "*string" {
			return "rt.Ptr(" + strconv.Quote(x) + ")", true
		}
	case bool:
		if goType == "bool" {
			return strconv.FormatBool(x), true
		}
	default:
		if isNumber(v) && numericGoType(goType) {
			return goType + "(" + goLiteral(v) + ")", true
		}
	}
	return "", false
}

// emitNode emits checks for value expr (Go type goType) against node n.
// fieldLevel marks a struct field, where presence was already tested and
// a nil pointer counts as absent rather than null.
func (g *gen) emitNode(n ir.TypeNode, expr, goType, pathVar, scopePV string, scope map[string]field, fieldLevel bool) {
	if strings.HasPrefix(goType, "*") {
		inner := strings.TrimPrefix(goType, "*")
		if !fieldLevel {
			g.w("\t\tif %s == nil {", expr)
			if !nullableOf(n) {
				g.w("\t\t\trt.Null(errs, %s.String())", pathVar)
			}
			g.w("\t\t} else {")
			g.emitNode(n, "(*"+expr+")", inner, pathVar, scopePV, scope, false)
			g.w("\t\t}")
			return
		}
		g.emitNode(n, "(*"+expr+")", inner, pathVar, scopePV, scope, false)
		return
	}
	switch t := n.(type) {
	case *ir.StringNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.IntNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.FloatNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.BoolNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.BytesNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.TimeNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.DurationNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
	case *ir.AnyNode:
		// Nothing to check.
	case *ir.ArrayNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
		elemType, ok := strings.CutPrefix(goType, "[]")
		if !ok {
			if i := strings.Index(goType, "]"); strings.HasPrefix(goType, "[") && i > 0 {
				elemType = goType[i+1:]
			} else {
				g.errf("array node on non-slice Go type %s", goType)
				return
			}
		}
		i := g.fresh("i")
		p := g.fresh("p")
		g.w("\t\tfor %s := range %s {", i, expr)
		g.stopCheck()
		g.w("\t\t\t%s := %s.Index(%s)", p, pathVar, i)
		g.w("\t\t\t_ = %s", p)
		g.emitNode(t.Elem, expr+"["+i+"]", elemType, p, scopePV, scope, false)
		g.w("\t\t}")
	case *ir.MapNode:
		g.emitRules(t.Rules, expr, goType, pathVar, scopePV, scope)
		keyType, valType, ok := splitMapType(goType)
		if !ok {
			g.errf("map node on non-map Go type %s", goType)
			return
		}
		k, e, p := g.fresh("k"), g.fresh("e"), g.fresh("p")
		g.w("\t\tfor %s, %s := range %s {", k, e, expr)
		g.stopCheck()
		switch {
		case keyType == "string":
			g.w("\t\t\t%s := %s.KeyStr(%s)", p, pathVar, k)
		case numericGoType(keyType) && !strings.HasPrefix(keyType, "float"):
			g.w("\t\t\t%s := %s.KeyInt(int(%s))", p, pathVar, k)
		default:
			g.w("\t\t\t%s := %s.Key(%s)", p, pathVar, k)
		}
		g.w("\t\t\t_ = %s", p)
		g.emitNode(t.Key, k, keyType, p, scopePV, scope, false)
		g.emitNode(t.Val, e, valType, p, scopePV, scope, false)
		g.w("\t\t}")
	case *ir.RefNode:
		if goType != t.Ref {
			g.errf("ref %s used on Go type %s", t.Ref, goType)
			return
		}
		tmp := g.fresh("r")
		g.w("\t\t%s := %s", tmp, expr)
		g.w("\t\tvalidate%s(ctx, &%s, reg, %s, errs)", t.Ref, tmp, pathVar)
	case *ir.ObjectNode:
		fields, ok := g.structFields(goType)
		if !ok {
			g.errf("inline object on Go type %s, which is not a struct in the package", goType)
			return
		}
		tmp := g.fresh("o")
		g.w("\t\t%s := %s", tmp, expr)
		g.w("\t\t{")
		g.emitObjectBody(t, "(&"+tmp+")", fields, pathVar)
		g.w("\t\t}")
	case *ir.UnionNode:
		g.emitUnion(t, expr, goType, pathVar, scopePV, scope)
	case *ir.OneOfNode:
		g.emitOneOf(t, expr, goType, pathVar, scopePV, scope)
	}
}

// emitUnion probes each variant in order on an interface-typed value; the
// first variant whose Go type matches and whose rules pass accepts it.
// Refs and inline objects are matched by concrete struct type (value or
// pointer); scalar variants through rt.As* probes.
func (g *gen) emitUnion(u *ir.UnionNode, expr, goType, pathVar, scopePV string, scope map[string]field) {
	isIface := goType == "any" || goType == "interface{}"
	// Variants codegen can probe natively; anything else sends the whole
	// union to the interpreter so the semantics stay exactly the
	// interpreter's (first matching variant wins).
	for _, variant := range u.Variants {
		switch variant.(type) {
		case *ir.ArrayNode, *ir.MapNode, *ir.ObjectNode, *ir.OneOfNode, *ir.UnionNode:
			g.emitFallback(u, expr, pathVar, "union with a "+string(variant.Kind())+" variant")
			return
		}
	}
	if !isIface {
		// A concrete field: only variants of that Go type can ever match,
		// and a probe on a typed value needs no type switch.
		ok := g.fresh("ok")
		g.w("\t\t%s := false", ok)
		matched := 0
		for _, variant := range u.Variants {
			if !variantFits(variant, goType) {
				continue
			}
			matched++
			probe, x := g.fresh("probe"), g.fresh("x")
			g.w("\t\tif !%s {", ok)
			g.w("\t\t\tvar %s verr.Errors", probe)
			g.w("\t\t\t%s.FailFast = true", probe)
			g.w("\t\t\t%s := %s", x, expr)
			g.w("\t\t\t_ = %s", x)
			g.w("\t\t\t{")
			g.withErrs(probe, func() {
				g.emitNode(variant, x, goType, pathVar, scopePV, scope, false)
			})
			g.w("\t\t\t\tif %s.Len() == 0 {", probe)
			g.w("\t\t\t\t\t%s = true", ok)
			g.w("\t\t\t\t}")
			g.w("\t\t\t}")
			g.w("\t\t}")
		}
		if matched == 0 {
			g.w("\t\t// no variant can match Go type %s; the value always fails the union", goType)
		}
		g.w("\t\tif !%s {", ok)
		g.w("\t\t\trt.Union(errs, %s.String(), %d)", pathVar, len(u.Variants))
		g.w("\t\t}")
		return
	}
	ok := g.fresh("ok")
	g.w("\t\t%s := false", ok)
	for _, variant := range u.Variants {
		probe, x := g.fresh("probe"), g.fresh("x")
		g.w("\t\tif !%s {", ok)
		// A stack-allocated, fail-fast probe: only "did anything fail"
		// matters, and no pointer to it outlives the block.
		g.w("\t\t\tvar %s verr.Errors", probe)
		g.w("\t\t\t%s.FailFast = true", probe)
		var vtype string
		switch vt := variant.(type) {
		case *ir.StringNode:
			g.w("\t\t\tif %s, matched := rt.AsString(%s); matched {", x, expr)
			vtype = "string"
		case *ir.IntNode, *ir.DurationNode:
			g.w("\t\t\tif %s, matched := rt.AsIntegral(%s); matched {", x, expr)
			vtype = "float64"
		case *ir.FloatNode:
			g.w("\t\t\tif %s, matched := rt.AsNumber(%s); matched {", x, expr)
			vtype = "float64"
		case *ir.BoolNode:
			g.w("\t\t\tif %s, matched := %s.(bool); matched {", x, expr)
			vtype = "bool"
		case *ir.BytesNode:
			g.w("\t\t\tif %s, matched := %s.([]byte); matched {", x, expr)
			vtype = "[]byte"
		case *ir.TimeNode:
			g.w("\t\t\tif %s, matched := %s.(time.Time); matched {", x, expr)
			g.imports["time"] = "time"
			vtype = "time.Time"
		case *ir.RefNode:
			g.w("\t\t\tif %s, matched := rt.AsStruct[%s](%s); matched {", x, vt.Ref, expr)
			vtype = "*" + vt.Ref
		case *ir.AnyNode:
			g.w("\t\t\tif %s, matched := %s, true; matched {", x, expr)
			vtype = "any"
		default:
			// Filtered above; kept so a new node kind cannot fall through
			// silently.
			g.errf("union variant %s is not supported by codegen (path %s)", variant.Kind(), pathVar)
			g.w("\t\t\tif %s, matched := %s, false; matched {", x, expr)
			vtype = "any"
		}
		g.w("\t\t\t\t_ = %s", x)
		g.withErrs(probe, func() {
			g.emitNode(variant, x, vtype, pathVar, scopePV, scope, false)
		})
		g.w("\t\t\t\tif %s.Len() == 0 {", probe)
		g.w("\t\t\t\t\t%s = true", ok)
		g.w("\t\t\t\t}")
		g.w("\t\t\t}")
		g.w("\t\t}")
	}
	g.w("\t\tif !%s {", ok)
	g.w("\t\t\trt.Union(errs, %s.String(), %d)", pathVar, len(u.Variants))
	g.w("\t\t}")
}

// emitFallback delegates one subtree to the interpreter. The subtree's IR
// (with the schema's defs, so refs resolve) is embedded as a package-level
// document parsed once at init; the value is validated at the current
// path through the shared interpreter, so issues are identical to a full
// interpreter run.
func (g *gen) emitFallback(n ir.TypeNode, expr, pathVar, why string) {
	sub := &ir.Schema{Version: ir.Version, Root: n, Defs: g.opts.Schema.Defs}
	doc, err := json.Marshal(sub)
	if err != nil {
		g.errf("cannot embed IR for fallback: %v", err)
		return
	}
	name := g.fresh("fallback")
	g.fallbacks = append(g.fallbacks, fallback{name: name, doc: string(doc), why: why})
	g.w("\t\t// %s: delegated to the interpreter (see %s).", why, name)
	g.w("\t\trt.Interpret(ctx, reg, %s, %s, &%s, errs)", name, expr, pathVar)
}

// variantFits reports whether a union variant can match a concrete Go
// type at all.
func variantFits(v ir.TypeNode, goType string) bool {
	switch v := v.(type) {
	case *ir.StringNode:
		return goType == "string"
	case *ir.IntNode, *ir.DurationNode:
		return numericGoType(goType) && !strings.HasPrefix(goType, "float")
	case *ir.FloatNode:
		return numericGoType(goType)
	case *ir.BoolNode:
		return goType == "bool"
	case *ir.BytesNode:
		return goType == "[]byte"
	case *ir.TimeNode:
		return goType == "time.Time"
	case *ir.RefNode:
		return goType == v.Ref || goType == "*"+v.Ref
	case *ir.AnyNode:
		return true
	}
	return false
}

// withErrs emits body with issues redirected into a probe error list.
// Generated code always appends to a variable named errs, so the probe
// shadows it for the duration of the block.
func (g *gen) withErrs(probe string, body func()) {
	g.w("				{")
	g.w("				errs := &%s", probe)
	g.w("				_ = errs")
	g.inProbe++
	body()
	g.inProbe--
	g.w("				}")
}

// emitOneOf switches on the discriminator field of a concrete struct.
// Each case is an inline object over the same Go type with its own rule
// set; an unknown tag routes to the default or reports unknown_variant.
func (g *gen) emitOneOf(o *ir.OneOfNode, expr, goType, pathVar, scopePV string, scope map[string]field) {
	fields, ok := g.structFields(goType)
	if !ok {
		// The discriminator lives in a value whose Go type is unknown
		// statically; only reflection can read it, so this subtree runs
		// under the interpreter.
		g.emitFallback(o, expr, pathVar, "discriminated union on Go type "+goType)
		return
	}
	disc, found := g.discriminatorField(goType, o.Discriminator)
	if !found {
		g.errf("oneof discriminator %q is not a field of %s", o.Discriminator, goType)
		return
	}
	if disc.goType != "string" {
		g.errf("oneof discriminator %s.%s must be a string field, got %s", goType, disc.name, disc.goType)
		return
	}
	tmp := g.fresh("o")
	g.w("\t\t%s := %s", tmp, expr)
	g.w("\t\tswitch %s.%s {", tmp, disc.name)
	tags := make([]string, 0, len(o.Cases))
	for t := range o.Cases {
		tags = append(tags, t)
	}
	sort.Strings(tags)
	for _, tag := range tags {
		g.w("\t\tcase %s:", strconv.Quote(tag))
		caseObj, isObj := o.Cases[tag].(*ir.ObjectNode)
		if !isObj {
			g.errf("oneof case %q is not an inline object (path %s)", tag, pathVar)
			continue
		}
		g.emitObjectBody(caseObj, "(&"+tmp+")", fields, pathVar)
	}
	g.w("\t\tdefault:")
	if o.Default != nil {
		g.emitNode(o.Default, tmp, goType, pathVar, scopePV, scope, false)
	} else {
		g.w("\t\t\trt.Variant(errs, %s.String(), %q, %s.%s)", pathVar, o.Discriminator, tmp, disc.name)
	}
	g.w("\t\t}")
}

// discriminatorField finds the struct field a wire-name discriminator
// refers to: json tag first, then Go name, then case-insensitive Go name —
// the interpreter's lookup order.
func (g *gen) discriminatorField(typeName, wire string) (field, bool) {
	decl, ok := g.pkg.Struct(typeName)
	if !ok {
		return field{}, false
	}
	fields, _ := g.structFields(typeName)
	for _, f := range decl.Type.Fields.List {
		if f.Tag == nil {
			continue
		}
		raw, err := strconv.Unquote(f.Tag.Value)
		if err != nil {
			continue
		}
		name, _, _ := strings.Cut(reflect.StructTag(raw).Get("json"), ",")
		if name == wire {
			for _, id := range f.Names {
				return fields[id.Name], true
			}
		}
	}
	if f, ok := fields[wire]; ok {
		return f, true
	}
	for name, f := range fields {
		if strings.EqualFold(name, wire) {
			return f, true
		}
	}
	return field{}, false
}

// emitRules emits one check per rule.
func (g *gen) emitRules(rs []ir.Rule, expr, goType, pathVar, scopePV string, scope map[string]field) {
	for i := range rs {
		r := &rs[i]
		if r.Cond != nil {
			cond, ok := g.condExpr(*r.Cond, scopePV, scope)
			if !ok {
				continue
			}
			g.w("\t\tif %s {", cond)
			g.emitRule(r, expr, goType, pathVar, scopePV, scope)
			g.w("\t\t}")
			continue
		}
		g.emitRule(r, expr, goType, pathVar, scopePV, scope)
	}
}

// emitRule emits `if !(pass) { fail }` for one rule.
func (g *gen) emitRule(r *ir.Rule, expr, goType, pathVar, scopePV string, scope map[string]field) {
	code, tmpl := rules.TextFor(r)
	params := goLiteral(r.Params)
	fail := fmt.Sprintf("rt.Fail(errs, %q, %s.String(), %q, %q, %s)", code, pathVar, tmpl, string(r.Kind), params)
	var pass string
	switch r.Kind {
	case ir.RuleMinLength:
		pass = fmt.Sprintf("%s >= %s", lenExpr(expr, goType), count(r))
	case ir.RuleMaxLength:
		pass = fmt.Sprintf("%s <= %s", lenExpr(expr, goType), count(r))
	case ir.RuleMinItems:
		pass = fmt.Sprintf("len(%s) >= %s", expr, count(r))
	case ir.RuleMaxItems:
		pass = fmt.Sprintf("len(%s) <= %s", expr, count(r))
	case ir.RuleUnique:
		if elem, ok := sliceElem(goType); ok && comparableScalar(elem) {
			pass = fmt.Sprintf("rt.UniqueOf(%s)", expr)
		} else {
			pass = fmt.Sprintf("rt.Unique(%s)", expr)
		}
	case ir.RuleMin, ir.RuleGte:
		pass = fmt.Sprintf("float64(%s) >= %s", expr, num(r))
	case ir.RuleMax, ir.RuleLte:
		pass = fmt.Sprintf("float64(%s) <= %s", expr, num(r))
	case ir.RuleGt:
		pass = fmt.Sprintf("float64(%s) > %s", expr, num(r))
	case ir.RuleLt:
		pass = fmt.Sprintf("float64(%s) < %s", expr, num(r))
	case ir.RuleMultipleOf:
		pass = fmt.Sprintf("rt.MultipleOf(float64(%s), %s)", expr, num(r))
	case ir.RulePattern:
		re, _ := r.Params[ir.ParamRegex].(string)
		name, seen := g.regexps[re]
		if !seen {
			name = g.fresh("pattern")
			g.regexps[re] = name
			g.regexOrder = append(g.regexOrder, re)
			g.imports["regexp"] = "regexp"
		}
		pass = fmt.Sprintf("%s.MatchString(%s)", name, expr)
	case ir.RuleEnum:
		values, _ := r.Params[ir.ParamValues].([]any)
		pass = g.membership(expr, goType, values)
	case ir.RuleConst:
		pass = g.membership(expr, goType, []any{r.Params[ir.ParamValue]})
	case ir.RuleEmail:
		pass = fmt.Sprintf("rt.Email(%s)", expr)
	case ir.RuleURL:
		pass = fmt.Sprintf("rt.URL(%s)", expr)
	case ir.RuleUUID:
		pass = fmt.Sprintf("rt.UUID(%s)", expr)
	case ir.RuleULID:
		pass = fmt.Sprintf("rt.ULID(%s)", expr)
	case ir.RuleIPv4, ir.RuleIPv6, ir.RuleIP, ir.RuleCIDR, ir.RuleMAC, ir.RuleHostname, ir.RuleBase64, ir.RuleJSON, ir.RuleSemver, ir.RuleDate, ir.RuleDateTime, ir.RuleNotBlank,
		ir.RuleCreditCard, ir.RuleJWT, ir.RuleCountryCode, ir.RuleCurrencyCode, ir.RuleHexColor, ir.RuleE164:
		pass = fmt.Sprintf("rt.%s(%s)", formatFunc[r.Kind], expr)
	case ir.RuleLatitude, ir.RuleLongitude:
		pass = fmt.Sprintf("rt.%s(float64(%s))", formatFunc[r.Kind], expr)
	case ir.RuleAfter, ir.RuleBefore:
		fieldName, _ := r.Params[ir.ParamField].(string)
		sib, ok := scope[fieldName]
		if !ok {
			g.errf("%s references unknown sibling %s", r.Kind, fieldName)
			return
		}
		sibExpr := scopePV + "." + sib.name
		method := "After"
		if r.Kind == ir.RuleBefore {
			method = "Before"
		}
		// The interpreter passes when the sibling is absent or not a time.
		if strings.HasPrefix(sib.goType, "*") {
			pass = fmt.Sprintf("(%s == nil || (*%s).IsZero() || %s.%s(*%s))", sibExpr, sibExpr, expr, method, sibExpr)
		} else {
			pass = fmt.Sprintf("(%s.IsZero() || %s.%s(%s))", sibExpr, expr, method, sibExpr)
		}
	case ir.RuleCustom, ir.RuleAsync:
		name, _ := r.Params[ir.ParamRef].(string)
		errVar := g.fresh("err")
		g.w("\t\tif %s := rt.Call(ctx, reg, %q, %s); %s != nil {", errVar, name, expr, errVar)
		g.w("\t\t\t%s := %s", g.fresh("params"), params)
		last := "params" + strconv.Itoa(g.seq)
		g.w("\t\t\t%s[\"error\"] = %s.Error()", last, errVar)
		g.w("\t\t\trt.Fail(errs, %q, %s.String(), %q, %q, %s)", code, pathVar, tmpl, string(r.Kind), last)
		g.w("\t\t}")
		return
	default:
		g.errf("rule %s has no code generator", r.Kind)
		return
	}
	g.w("\t\tif !(%s) {", pass)
	g.w("\t\t\t%s", fail)
	g.w("\t\t}")
}

// emitGate emits object-level conditional logic.
func (g *gen) emitGate(obj *ir.ObjectNode, gate ir.GatedRules, pv string, fields map[string]field, pathVar string) {
	switch gate.Kind {
	case ir.GateWhen:
		cond, ok := g.condExpr(*gate.Cond, pv, fields)
		if !ok {
			return
		}
		g.w("\tif %s {", cond)
		g.emitTargets(obj, gate.Then, pv, fields, pathVar)
		g.w("\t} else {")
		g.emitTargets(obj, gate.Else, pv, fields, pathVar)
		g.w("\t}")
	case ir.GateRequires:
		cond, ok := g.condExpr(*gate.Cond, pv, fields)
		if !ok {
			return
		}
		g.w("\tif %s {", cond)
		for _, name := range gate.Fields {
			gf, ok := fields[name]
			if !ok {
				g.errf("requires names unknown field %s", name)
				continue
			}
			g.w("\t\tif !(%s) {", presenceExpr(pv+"."+gf.name, gf.goType))
			rp := g.fresh("p")
			g.w("\t\t\t%s := %s.Field(%q)", rp, pathVar, "."+wireOfGo(obj, name))
			g.w("\t\t\trt.Required(errs, %s.String())", rp)
			g.w("\t\t}")
		}
		g.w("\t}")
	case ir.GateGroup:
		cnt := g.fresh("n")
		g.w("\t%s := 0", cnt)
		for _, name := range gate.Fields {
			gf, ok := fields[name]
			if !ok {
				g.errf("group names unknown field %s", name)
				continue
			}
			g.w("\tif %s {", presenceExpr(pv+"."+gf.name, gf.goType))
			g.w("\t\t%s++", cnt)
			g.w("\t}")
		}
		var okExpr string
		switch gate.Mode {
		case ir.ExactlyOne:
			okExpr = cnt + " == 1"
		case ir.AtLeastOne:
			okExpr = cnt + " >= 1"
		case ir.AllOrNone:
			okExpr = fmt.Sprintf("(%s == 0 || %s == %d)", cnt, cnt, len(gate.Fields))
		}
		g.w("\tif !(%s) {", okExpr)
		g.w("\t\trt.Group(errs, %s.String(), %q, %s, %s)", pathVar, string(gate.Mode), goLiteral(gate.Fields), cnt)
		g.w("\t}")
	}
}

// emitTargets applies gated rules to fields, checking the zero value when
// the field is absent — the interpreter's "required when" reading.
func (g *gen) emitTargets(obj *ir.ObjectNode, ts []ir.TargetRule, pv string, fields map[string]field, pathVar string) {
	for _, tr := range ts {
		gf, ok := fields[tr.Field]
		if !ok {
			g.errf("gated rule targets unknown field %s", tr.Field)
			continue
		}
		x, p := g.fresh("x"), g.fresh("p")
		goType := gf.goType
		expr := pv + "." + gf.name
		g.w("\t{")
		g.w("\t\t%s := %s.Field(%q)", p, pathVar, "."+wireOfGo(obj, tr.Field))
		g.w("\t\t_ = %s", p)
		if strings.HasPrefix(goType, "*") {
			inner := strings.TrimPrefix(goType, "*")
			g.noteTypeImports(inner, gf.decl.Imports)
			g.w("\t\tvar %s %s", x, inner)
			g.w("\t\tif %s != nil {", expr)
			g.w("\t\t\t%s = *%s", x, expr)
			g.w("\t\t}")
			goType = inner
		} else {
			g.w("\t\t%s := %s", x, expr)
		}
		g.emitRules([]ir.Rule{tr.Rule}, x, goType, p, pv, fields)
		g.w("\t}")
	}
}

// condExpr renders a condition as a Go boolean expression.
func (g *gen) condExpr(k ir.Condition, pv string, fields map[string]field) (string, bool) {
	switch k.Kind {
	case ir.CondCmp:
		f, ok := fields[k.Field]
		if !ok {
			g.errf("condition references unknown field %s", k.Field)
			return "", false
		}
		return guarded(presenceExpr(pv+"."+f.name, f.goType), g.compare(pv+"."+f.name, f.goType, k.Value, ir.CmpOp(k.Op))), true
	case ir.CondFieldCmp:
		a, okA := fields[k.Field]
		b, okB := fields[k.FieldB]
		if !okA || !okB {
			g.errf("condition references unknown field %s or %s", k.Field, k.FieldB)
			return "", false
		}
		return guarded(presenceExpr(pv+"."+a.name, a.goType),
			guarded(presenceExpr(pv+"."+b.name, b.goType), g.compareFields(pv+"."+a.name, a.goType, pv+"."+b.name, b.goType, ir.CmpOp(k.Op)))), true
	case ir.CondPresence:
		f, ok := fields[k.Field]
		if !ok {
			g.errf("condition references unknown field %s", k.Field)
			return "", false
		}
		p := presenceExpr(pv+"."+f.name, f.goType)
		if ir.PresenceOp(k.Op) == ir.Absent {
			return "!(" + p + ")", true
		}
		return "(" + p + ")", true
	case ir.CondIn:
		f, ok := fields[k.Field]
		if !ok {
			g.errf("condition references unknown field %s", k.Field)
			return "", false
		}
		return guarded(presenceExpr(pv+"."+f.name, f.goType), g.membership(pv+"."+f.name, f.goType, k.Values)), true
	case ir.CondAnd, ir.CondOr:
		parts := make([]string, 0, len(k.Sub))
		for _, sub := range k.Sub {
			s, ok := g.condExpr(sub, pv, fields)
			if !ok {
				return "", false
			}
			parts = append(parts, s)
		}
		sep := " && "
		if k.Kind == ir.CondOr {
			sep = " || "
		}
		return "(" + strings.Join(parts, sep) + ")", true
	case ir.CondNot:
		s, ok := g.condExpr(k.Sub[0], pv, fields)
		if !ok {
			return "", false
		}
		return "!" + s, true
	case ir.CondCustom:
		return fmt.Sprintf("rt.Cond(ctx, reg, %q, *%s)", k.Ref, pv), true
	}
	g.errf("condition %s is not supported by codegen yet", k.Kind)
	return "", false
}

// membership renders an enum/const check. When the Go type and every
// literal agree on a scalar kind the check is an inline switch — no boxing,
// no allocation; otherwise it falls back to the normalized rt.In.
func (g *gen) membership(expr, goType string, values []any) string {
	if goType == "string" && allStrings(values) {
		parts := make([]string, len(values))
		for i, v := range values {
			parts[i] = fmt.Sprintf("%s == %s", expr, strconv.Quote(v.(string)))
		}
		return "(" + strings.Join(parts, " || ") + ")"
	}
	if numericGoType(goType) && allNumbers(values) {
		parts := make([]string, len(values))
		for i, v := range values {
			parts[i] = fmt.Sprintf("float64(%s) == %s", expr, floatLiteral(v))
		}
		return "(" + strings.Join(parts, " || ") + ")"
	}
	if goType == "bool" && len(values) == 1 {
		if b, ok := values[0].(bool); ok {
			return fmt.Sprintf("(%s == %t)", expr, b)
		}
	}
	name := g.hoist(goLiteral(values))
	return fmt.Sprintf("rt.In(%s, %s)", expr, name)
}

// compare renders an ordered comparison against a literal, inline when
// the Go type and literal are both numeric or both strings.
func (g *gen) compare(expr, goType string, value any, op ir.CmpOp) string {
	goOp := map[ir.CmpOp]string{ir.OpEq: "==", ir.OpNe: "!=", ir.OpGt: ">", ir.OpGte: ">=", ir.OpLt: "<", ir.OpLte: "<="}[op]
	if numericGoType(goType) && isNumber(value) {
		return fmt.Sprintf("float64(%s) %s %s", expr, goOp, floatLiteral(value))
	}
	if s, ok := value.(string); ok && goType == "string" {
		return fmt.Sprintf("%s %s %s", expr, goOp, strconv.Quote(s))
	}
	return fmt.Sprintf("rt.Compare(%s, %s, %q)", expr, goLiteral(value), string(op))
}

// compareFields renders a field-to-field comparison inline when both
// sides are numeric or both strings; times and mixed types go through the
// shared rt.Compare.
func (g *gen) compareFields(a, aType, b, bType string, op ir.CmpOp) string {
	goOp := map[ir.CmpOp]string{ir.OpEq: "==", ir.OpNe: "!=", ir.OpGt: ">", ir.OpGte: ">=", ir.OpLt: "<", ir.OpLte: "<="}[op]
	if numericGoType(aType) && numericGoType(bType) {
		return fmt.Sprintf("float64(%s) %s float64(%s)", a, goOp, b)
	}
	if aType == "string" && bType == "string" {
		return fmt.Sprintf("%s %s %s", a, goOp, b)
	}
	return fmt.Sprintf("rt.Compare(%s, %s, %q)", a, b, string(op))
}

// hoist stores a literal expression in a package-level var so it is built
// once, and returns the var name.
func (g *gen) hoist(literal string) string {
	if name, ok := g.hoisted[literal]; ok {
		return name
	}
	name := g.fresh("lit")
	g.hoisted[literal] = name
	g.hoistOrder = append(g.hoistOrder, literal)
	return name
}

func allStrings(values []any) bool {
	for _, v := range values {
		if _, ok := v.(string); !ok {
			return false
		}
	}
	return len(values) > 0
}

func allNumbers(values []any) bool {
	for _, v := range values {
		if !isNumber(v) {
			return false
		}
	}
	return len(values) > 0
}

func isNumber(v any) bool {
	switch v.(type) {
	case int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64, float32, float64:
		return true
	}
	return false
}

// floatLiteral renders any numeric literal as a float64 constant.
func floatLiteral(v any) string {
	return "float64(" + goLiteral(v) + ")"
}

// numericGoType reports the Go numeric types the generator compares
// through float64, including time.Duration (an int64).
func numericGoType(goType string) bool {
	switch goType {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64", "time.Duration":
		return true
	}
	return false
}

// sliceElem returns the element type of a slice type expression.
func sliceElem(goType string) (string, bool) {
	return strings.CutPrefix(goType, "[]")
}

// comparableScalar reports whether a Go type can key a map without
// reflection: the scalar kinds and pointers.
func comparableScalar(goType string) bool {
	return numericGoType(goType) || goType == "string" || goType == "bool" || strings.HasPrefix(goType, "*") || goType == "time.Time"
}

// guarded conjoins a presence test with an expression, dropping the test
// when it is the constant true so vet never sees `true && x`.
func guarded(presence, expr string) string {
	if presence == "true" {
		return "(" + expr + ")"
	}
	return "(" + presence + " && " + expr + ")"
}

// presenceExpr renders the interpreter's presence rule for a Go type.
func presenceExpr(expr, goType string) string {
	switch {
	case strings.HasPrefix(goType, "*"), strings.HasPrefix(goType, "[]"), strings.HasPrefix(goType, "map["):
		return expr + " != nil"
	case goType == "string":
		return expr + ` != ""`
	case goType == "time.Time":
		return "!" + expr + ".IsZero()"
	case goType == "any", goType == "interface{}":
		return "rt.Present(" + expr + ")"
	}
	return "true"
}

// lenExpr is the length measure for a length rule: runes for strings,
// bytes for byte slices.
func lenExpr(expr, goType string) string {
	if goType == "string" {
		return "rt.RuneLen(" + expr + ")"
	}
	return "len(" + expr + ")"
}

